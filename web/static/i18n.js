const LANG_KEY = 'lingolens.lang';
let lang = 'en';
try {
  const saved = localStorage.getItem(LANG_KEY);
  if (saved === 'zh' || saved === 'en') lang = saved;
} catch { /* storage unavailable */ }

export function getLang() {
  return lang;
}

export function setLang(next) {
  lang = next === 'zh' ? 'zh' : 'en';
  try { localStorage.setItem(LANG_KEY, lang); } catch { /* ignore */ }
  applyI18n();
}

// t('key', {n: 3}) -> translated string with {placeholders} filled in.
export function t(key, vars) {
  const v = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  if (typeof v !== 'string' || !vars) return v;
  return v.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}

// Fill elements marked with data-i18n, data-i18n-placeholder, data-i18n-title, data-i18n-aria.
export function applyI18n(root = document) {
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-placeholder]')) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of root.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
  for (const el of root.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
}
