// Generates words.txt: the words each level counts as known, so they never get a
// gloss (see Level.Knows). It comes from ECDICT's exam lists and frequency ranks:
//
//	curl -LO https://raw.githubusercontent.com/skywind3000/ECDICT/39cfb9672c0906b63569e0453c2e6abfb9ab182a/ecdict.csv
//	go run genwords.go ecdict.csv > words.txt
//
// Bump annotate.PromptVersion after changing the result, so saved glosses are redone.
package main

import (
	"encoding/csv"
	"fmt"
	"io"
	"log"
	"os"
	"slices"
	"strconv"
	"strings"
)

// The exam lists, easiest first.
var ladder = []string{"zk", "gk", "cet4", "cet6", "ky", "toefl", "ielts", "gre"}

// A level counts a word as known if the word is on the exam lists one step below
// the level, or common enough. This stays well inside what each level claims to
// know: above it, the model decides. Rarer words on a list are left to the model
// too (a C1 reader may well not know "tensile", though it is on the CET-6 list).
var rules = []struct {
	level    string
	lists    []string // ECDICT tags
	rareFrom int      // a listed word ranked beyond this doesn't count; 0: no limit
	common   int      // a word ranked this high counts too...
	reach    int      // ...unless its exam lists all lie beyond this many steps of the ladder
	unlisted bool     // ...and it may be on no exam list at all
}{
	{"A1", nil, 0, 150, 1, false},
	{"A2", nil, 0, 600, 1, false},
	{"B1", []string{"zk"}, 0, 1500, 2, true},
	{"B2", []string{"gk"}, 0, 3000, 4, true},
	{"C1", []string{"cet4", "cet6"}, 15000, 6000, 7, true},
	{"C2", []string{"ky", "toefl", "ielts"}, 20000, 10000, 8, true},
}

// Everyday words too new for the exam lists and the frequency ranks.
var modern = map[string][]string{
	"B1": {"app", "apps", "download", "email", "laptop", "online", "password", "smartphone", "upload", "website", "wifi"},
	"B2": {"blog", "browser", "ebook", "emoji", "hashtag", "login", "logout", "offline", "podcast", "selfie", "startup", "username"},
}

