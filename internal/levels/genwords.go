func plainWord(w string) bool {
	if len(w) < 2 {
		return false
	}
	for _, c := range w {
		if c < 'a' || c > 'z' {
			return false
		}
	}
	return true
}

func main() {
	f, err := os.Open(os.Args[1])
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()
	r := csv.NewReader(f)
	r.LazyQuotes = true
	r.FieldsPerRecord = -1
	head, err := r.Read()
	if err != nil {
		log.Fatal(err)
	}
	col := func(name string) int {
		i := slices.Index(head, name)
		if i < 0 {
			log.Fatalf("no column %q", name)
		}
		return i
	}
	wordCol, tagCol, frqCol := col("word"), col("tag"), col("frq")

	byLevel := map[string][]string{}
	seen := map[string]bool{}
	add := func(level, w string) {
		if !seen[w] {
			seen[w] = true
			byLevel[level] = append(byLevel[level], w)
		}
	}
	type entry struct {
		word string
		tags []string
		rank int
	}
	var entries []entry
	for {
		rec, err := r.Read()
		if err == io.EOF {
			break
		}
		if err != nil {
			log.Fatal(err)
		}
		if len(rec) <= frqCol || !plainWord(rec[wordCol]) {
			continue
		}
		rank, _ := strconv.Atoi(rec[frqCol])
		entries = append(entries, entry{rec[wordCol], strings.Fields(rec[tagCol]), rank})
	}
	for _, rule := range rules {
		for _, e := range entries {
			listed := slices.ContainsFunc(rule.lists, func(l string) bool { return slices.Contains(e.tags, l) })
			if rule.rareFrom > 0 && e.rank > rule.rareFrom {
				listed = false
			}
			common := e.rank > 0 && e.rank <= rule.common
			if len(e.tags) == 0 {
				common = common && rule.unlisted
			} else {
				common = common && slices.ContainsFunc(ladder[:rule.reach], func(l string) bool { return slices.Contains(e.tags, l) })
			}
			if listed || common {
				add(rule.level, e.word)
			}
		}
		for _, w := range modern[rule.level] {
			add(rule.level, w)
		}
	}

	fmt.Print(header)
	for _, rule := range rules {
		slices.Sort(byLevel[rule.level])
		fmt.Printf("\n[%s]\n%s\n", rule.level, strings.Join(byLevel[rule.level], "\n"))
	}
}
